#!/usr/bin/env python3
"""Generate docs/CONSTITUTION.md — the live-readable derived view of soul.md.

Why this exists (P2, halt prerequisite, 2026-11-14, issue #243): the live Hive
reads its constitution through the Worker's ASSETS binding, and ASSETS serves
only docs/ (wrangler.jsonc). The canonical constitution, soul.md (F-001–F-006
only), sits at the repo root — outside docs/ — so the live system cannot fetch
it. constitutionSummary() therefore read docs/GOVERNANCE.md, which presents
F-001–F-013 as "immutable core articles". F-007–F-013 are unratified, so the
live Hive was grounding on non-canonical law — the availability audit's most
serious finding.

XR-Q29 (decided 2026-11-12) is the authority for this file: soul.md is the ONE
constitution, and docs/GOVERNANCE.md and .queen/soul.md are DECLARED DERIVED
VIEWS, generated from soul.md — never hand-written separately, so they can
never drift from it. This script is the generator for the live path's derived
view, docs/CONSTITUTION.md.

The view is soul.md VERBATIM, plus a generated header that says, in plain
words, that it is a view of soul.md and not the constitution itself (XR-Q29's
own requirement). Zero transformation of the body means zero drift: the
invariant "the body of docs/CONSTITUTION.md == soul.md, byte for byte" is
checkable by this script (--check), by worker/test/constitution.test.js, and
by anyone with diff. The header carries the source sha256, so a stale view is
VISIBLE: if soul.md changes and this script is not re-run, the header's hash
no longer matches soul.md.

Why a NEW file (docs/CONSTITUTION.md) instead of regenerating
docs/GOVERNANCE.md itself: GOVERNANCE.md's F-007–F-013 articles are not in
soul.md, so no generator can derive them from soul.md — regenerating it would
either delete content the Constitution UI panel and live code still reference
or invent content not in the source. Both are wrong. GOVERNANCE.md's own
regeneration into a declared derived view is a separate decision, after the
F-007–F-013 question is settled (the law stress-test program, sequence #4).
This file is additive: a new file, a new route (GET /v11/constitution), a
repoint of constitutionSummary() — GOVERNANCE.md itself is untouched.

Usage:
    python3 scripts/generate-constitution-view.py            # write docs/CONSTITUTION.md
    python3 scripts/generate-constitution-view.py --check    # exit 0 if the view is fresh, 1 if stale/missing
Exit: 0 = wrote the view / the view is fresh; 1 = --check found it stale or
missing, or soul.md could not be read. The script is idempotent: re-running it
with an unchanged soul.md produces byte-identical output, and it does not
rewrite the file when the content already matches (so mtime stays clean).
"""

import hashlib
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SOURCE = REPO_ROOT / "soul.md"
TARGET = REPO_ROOT / "docs" / "CONSTITUTION.md"

FIXED_LAW_HEADING = re.compile(r"^###\s+(F-\d+):", re.MULTILINE)

HEADER_TEMPLATE = """> **GENERATED FILE — DO NOT HAND-EDIT.**
> This is a DERIVED VIEW of the canonical constitution, `soul.md`.
> It is NOT the constitution itself. `soul.md` is the ONE constitution (XR-Q29, decided 2026-11-12).
> Fixed laws in this view: {fixed_laws}.
> Generated by `scripts/generate-constitution-view.py` from `soul.md` (sha256: {source_sha}).
> To update: edit `soul.md` (through the Chromosome I process — founder proposes, own PR, founder merges),
> then re-run `python3 scripts/generate-constitution-view.py`.

---
"""


def render(source_text):
    """The derived view: generated header + soul.md verbatim."""
    source_sha = hashlib.sha256(source_text.encode("utf-8")).hexdigest()
    fixed_laws = ", ".join(FIXED_LAW_HEADING.findall(source_text))
    header = HEADER_TEMPLATE.format(source_sha=source_sha, fixed_laws=fixed_laws)
    return header + "\n" + source_text


def main(argv):
    check_only = "--check" in argv[1:]
    try:
        source_text = SOURCE.read_text(encoding="utf-8")
    except OSError as e:
        print(f"generate-constitution-view: cannot read {SOURCE}: {e}", file=sys.stderr)
        return 1
    if not FIXED_LAW_HEADING.search(source_text):
        print(
            "generate-constitution-view: soul.md has no '### F-NNN:' fixed-law "
            "headings — refusing to generate a view of a constitution with no "
            "fixed laws. If the constitution's shape changed deliberately, "
            "update this script first.",
            file=sys.stderr,
        )
        return 1
    expected = render(source_text)
    if check_only:
        try:
            actual = TARGET.read_text(encoding="utf-8")
        except OSError:
            print(
                f"generate-constitution-view: STALE — {TARGET} is missing. "
                "Run: python3 scripts/generate-constitution-view.py",
                file=sys.stderr,
            )
            return 1
        if actual == expected:
            print(f"generate-constitution-view: OK — {TARGET} is fresh.")
            return 0
        print(
            f"generate-constitution-view: STALE — {TARGET} does not match what "
            "soul.md generates (soul.md changed, or the view was hand-edited). "
            "Run: python3 scripts/generate-constitution-view.py",
            file=sys.stderr,
        )
        return 1
    if TARGET.exists() and TARGET.read_text(encoding="utf-8") == expected:
        print(f"generate-constitution-view: {TARGET} is already up to date.")
        return 0
    TARGET.write_text(expected, encoding="utf-8")
    # Verify the write: read it back and confirm it is exactly what was computed.
    if TARGET.read_text(encoding="utf-8") != expected:
        print(
            f"generate-constitution-view: wrote {TARGET} but the read-back "
            "does not match — the file is not trustworthy. Inspect it by hand.",
            file=sys.stderr,
        )
        return 1
    print(f"generate-constitution-view: wrote {TARGET} ({len(expected)} bytes).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
